/**
 * @file Build step — inlines the standalone dist bundle (minified CSS + IIFE
 * JS) as JS string constants consumed by the config builder page. This lets
 * `pages/app.js` build the "Baixar ZIP" download with zero runtime fetch —
 * fetch()/XHR to local files is blocked by CORS when the page itself is
 * opened via `file://`, but a classic <script> with the content already
 * inlined is not subject to that restriction.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { paths } from '../config.js'

/** Writes `pages/dist-assets.generated.js` from the already-built dist bundle. */
export function writePagesDistAssets() {
  const css = readFileSync(join(paths.dist, 'editor.min.css'), 'utf8')
  const js = readFileSync(join(paths.dist, 'editor.standalone.min.js'), 'utf8')

  const content = `// Auto-generated by scripts/build/steps/pages-assets.js from dist/ — do not edit.
// Loaded as a classic script (not a module) so it works the same way over
// HTTP and via file://. See pages/app.js for how it's consumed.
const DIST_ASSETS = {
  'editor.min.css': ${JSON.stringify(css)},
  'editor.standalone.min.js': ${JSON.stringify(js)},
}
`

  writeFileSync(join(paths.root, 'pages', 'dist-assets.generated.js'), content)
}
